"""전역 파라미터 — D09 §05 확정값 표를 그대로 옮긴다.

여기 있는 값을 바꾸면 설계도와 어긋난다. 바꿀 때는 D09도 함께 고친다.
"""

from dataclasses import dataclass

import torch

# ── 오디오 ────────────────────────────────────────────────────────────────────
SAMPLE_RATE = 16_000

# ── 청크 파이프라인 (D09 §04) ─────────────────────────────────────────────────
CHUNK_SEC = 2.0          # Resemblyzer partial utterance 1.6초 → 온전한 임베딩 1.25개
HOP_SEC = 1.0            # 50% 겹침. Hann overlap-add로 경계 클릭음 방지

# ── STFT ──────────────────────────────────────────────────────────────────────
# hop = n_fft/4 로 두어 Hann 창의 COLA 조건을 만족시킨다.
# 위반하면 ISTFT 왕복에서 진폭이 틀어지고 test_stft_roundtrip이 잡는다.
N_FFT = 512
HOP_LENGTH = 128

# ── PGD (D09 §05) ─────────────────────────────────────────────────────────────
PGD_STEPS = 200          # 서버 여유가 커서 표준 100의 2배
#
# alpha는 sign(gradient) 스텝 크기다. 매 스텝 정규화가 크기를 되돌리므로
# "한 스텝에 방향을 얼마나 바꾸는가"를 정한다.
# 절제 실험(합성 신호 · 50스텝)에서 1e-4는 전 배율 구간에서 1e-3보다 뚜렷하게 열등했다.
#   배율 0.75  SRS 0.987(1e-4) vs 0.906(1e-3)
#   배율 3.00  SRS 0.787       vs 0.462
#   배율 100   SRS 0.641       vs 0.351
# → 1e-3을 기본값으로 둔다. **실제 사람 목소리로 다시 스윕해 확정할 것.**
PGD_ALPHA = 1e-3

# ── 지각 제약 ─────────────────────────────────────────────────────────────────
TARGET_SNR_DB = 20.0     # 목표 SNR ≥ 20 dB. 정규화는 루프 안, 투영 앞
#
# 마스킹 배율은 D09에서 "청취 평가 후 결정"으로 열려 있는 유일한 파라미터다.
#
# 실제 음성 · 조건당 5회 · 50스텝으로 다시 쟀다 (`sweep_params.py`).
# 이겨야 할 대조군은 C-B 대역제한잡음 0.7146 ±0.0110.
#
#   배율   SRS (n=5)          판정              마스킹 임계값 위반 bin
#   0.75   0.8924 ±0.0138     ✗ 잡음보다 나쁨          0.44%
#   1.50   0.7296 ±0.0123     ? 우위 미확인 (구간 겹침) 17.78%
#   3.00   0.4907 ±0.0114     ✓ +0.224                23.45%
#   6.00   0.3255 ±0.0037     ✓ +0.389                24.48%
#  10.00   0.2681 ±0.0063     ✓ +0.446                24.28%
#
# **안 들리면서 잡음을 이기는 지점이 이 범위에 없다.**
# 위반 비율이 0.75 → 1.5 구간에서 0.44% → 17.8%로 40배 뛰고,
# 대조군을 이기는 최소 지점(3.0)에서는 이미 bin의 23%가 임계값을 넘는다.
# 청취 평가가 정할 것은 배율이 아니라 **어느 쪽을 포기할지**다.
#
# 잠정값을 3.0으로 둔다 — "잡음보다 낫다"를 유지하는 최소 배율이다.
# 확정은 청취 평가로 가청도 상한을 정한 뒤에 한다 (D07 W1 · 4h).
#
# 주의 — 위 "위반 bin"은 **절대 기준**(thr × 1.0)이다. 파이프라인이 한동안 보고하던
# 제약 기준(thr × ratio)은 배율이 커지면 기준선도 커져 초과량이 줄어든다.
# 그 열만 보면 "배율을 올릴수록 덜 들린다"는 정반대 결론이 나온다.
MASKING_RATIO = 3.0

BAND_LOW_HZ = 300.0      # 통화 대역. 밖은 코덱에서 어차피 제거된다
BAND_HIGH_HZ = 3400.0
BAND_TAPER_HZ = 50.0     # 브릭월 링잉 방지용 전이대역

# 통화 채널을 최적화 루프 안에 넣을지 (`codec_test.py`가 필요성을 실측으로 보였다).
#
# 섭동은 **전대역 원본**의 임베딩에서 멀어지도록 최적화된다. 그런데 실제 경로에서는
# 상대방이 듣는 것이 통화 채널을 통과한 신호다. 채널이 원본을 300~3400 Hz로 자르면
# 그 임베딩이 크게 이동하고(자기유사도 0.75), 최적화한 방향은 더 이상 적대적이지 않다.
#
# 실측 — 무처리 SRS 0.6342 → 대역 제한 후 0.8420 → G.711 협대역 0.8346.
# **채널을 통과시키자 방어가 판정 임계값 위로 되돌아왔다.**
# 섭동 자체는 남아 있었다(잔존 101% · 구조 상관 0.989). 지워진 게 아니라
# **표적이 틀렸던 것**이다.
#
# True면 손실을 `encoder(channel(x+δ))` 대 `encoder(channel(x))`로 계산한다.
# 즉 "상대방이 실제로 듣게 될 신호"에서 멀어지도록 최적화한다.
CHANNEL_AWARE = True

# ── VAD ───────────────────────────────────────────────────────────────────────
VAD_FRAME_MS = 10.0      # 에너지 기반 10 ms
VAD_FADE_MS = 8.0        # 경계 5~10 ms 페이드 — delta*mask 계단 끊김이 클릭음이 된다
VAD_REL_THRESH_DB = 30.0 # 프레임 최대 에너지 대비 -30 dB 아래를 무음으로 본다

# ── 수치 안정 ─────────────────────────────────────────────────────────────────
EPS = 1e-12              # 투영식 0-나눗셈 방지. 이 값이 없으면 무음 구간에서 NaN이 난다


def default_device() -> torch.device:
    """실구현은 RTX 3060, 개발 PC는 CPU. 어느 쪽이든 같은 코드가 돈다."""
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


@dataclass
class PGDConfig:
    """PGD 1회 실행에 필요한 값 묶음. 실험 시 이 객체만 바꿔 스윕한다."""

    steps: int = PGD_STEPS
    alpha: float = PGD_ALPHA
    target_snr_db: float = TARGET_SNR_DB
    masking_ratio: float = MASKING_RATIO
    band_low_hz: float = BAND_LOW_HZ
    band_high_hz: float = BAND_HIGH_HZ
    n_fft: int = N_FFT
    hop_length: int = HOP_LENGTH

    # STFT 투영만으로는 마스킹 불변식이 완전히 서지 않는다(perturbation.enforce_masking_bound 참조).
    # True면 마지막에 전역 축소로 불변식을 강제한다 — 들리지 않음이 보장되는 대신 방어가 약해진다.
    # False면 강도를 유지하고 초과량을 metrics.audibility로 정직하게 보고한다.
    # 어느 쪽을 쓸지는 청취 평가로 정한다.
    enforce_masking: bool = False

    # 손실을 "상대방이 실제로 듣게 될 신호"에서 계산한다. 위 CHANNEL_AWARE 주석 참조.
    channel_aware: bool = CHANNEL_AWARE
