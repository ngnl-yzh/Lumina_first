"""한국어 형태 규칙 — 표현을 세지 말고 구성을 세라.

## 왜 만들었나

검증셋을 네 번 만들어 네 번 다 결함이 나왔다. 그런데 되풀이해서 나온
결함의 성격이 하나였다 — **빠진 것은 사기 수법이 아니라 한국어 형태였다.**

    "가족에게 이 사실을 알리지 마세요"      어절 사이 삽입      1차
    "형수님한테는 말하지 말고"              임의의 호칭         1차
    "창구 직원에게는 말씀하지 마세요"        말하→말씀하        3차
    "부모님께는 알리지 마세요"              높임 조사 '께'      4차
                                           '말하지'는 있고
                                           '알리지'는 없음

넷 다 사기범이 노려서 쓴 회피가 아니다. **그냥 말하면 이렇게 된다.**
그때마다 표현을 하나씩 더 넣었지만, 한국어는 교착어라 어간 하나에
조사·어미가 자유롭게 붙는다. 표면형을 나열하는 방식으로는 끝이 없다.

## 어떻게 다루나

이 결함들은 전부 **생산적 구성**이다. 열린 자리(누구에게)와 닫힌 자리
(조사·어간·어미)로 이루어져 있고, 닫힌 자리는 셀 수 있다.

    [대상]  +  에게/한테/께/에  (는/도/만)  +  …  +  말하/알리/…  +  지 마/면 안
     열림          닫힘 4개        닫힘 4개        닫힘 12개        닫힘 8개

열린 자리를 요구하지 않는 것이 핵심이다. 호칭은 무한하다 —
형수님·아드님·사모님·과장님·담당자님. 그래서 **호칭을 빼고 나머지로** 잡는다.

닫힌 자리들을 곱하면 표면형이 수백 개가 된다. 그걸 다 문자열로 찾으면
발화당 비용이 감당이 안 된다. 그래서 정규식 하나로 컴파일한다 —
패턴당 한 번만 훑는다.

## 정규화된 텍스트 위에서 돈다

`normalize()`가 공백을 지우므로 규칙도 공백 없는 문자열을 가정한다.
띄어쓰기는 STT가 가장 못 믿을 정보라, 이렇게 하면 그 변수가 통째로 사라진다.
문자 인덱스가 곧 음절 인덱스여서 `MatchSpan`을 바로 만들 수 있고,
인용·고지·서술 판정(`context.py`)이 키워드와 똑같이 적용된다.

## 한계

형태소 분석기가 아니다. 어간을 진짜로 자르는 것이 아니라 **어간의 표기를
열거**하고 뒤에 올 수 있는 것을 제한할 뿐이다. KoNLPy 같은 분석기를 쓰면
더 정확하겠지만, 통화 중 실시간이라는 제약과 설치 부담을 생각하면
닫힌 자리를 직접 적는 편이 예측 가능하다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .matcher import MatchSpan, normalize

# ── 닫힌 자리 ─────────────────────────────────────────────────────────────────

#: 여격 조사 — "누구에게"를 나타낸다.
#: '에'는 단독으로 너무 흔하지만("계좌에", "오늘에"), 이 규칙은 뒤에
#: 함구 동사와 부정형이 반드시 오도록 묶으므로 안전하다.
DATIVE = ("에게", "한테", "께", "보고", "에")

#: 보조사 — 있어도 없어도 된다.
TOPIC = ("는", "도", "만", "라도", "")

#: 함구 동사의 어간 표기.
#: '말씀하'가 빠져 "창구 직원에게는 말씀하지 마세요"를 놓쳤고(3차),
#: '알리'가 빠져 "부모님께는 알리지 마세요"를 놓쳤다(4차).
SILENCE_STEMS = (
    "말하", "말씀하", "얘기하", "이야기하", "언급하",
    "알리", "알려주", "알려드리", "전하", "전달하",
    "발설하", "누설하", "밝히",
)

#: 부정 어미. "-지 마/말/않"과 "-면 안"이 한국어 금지의 두 축이다.
NEGATION = ("지마", "지말", "지않", "지못", "면안", "시면안", "지마시", "지마세")

#: 겸양 보조동사 — **화자가** 준다는 뜻이다.
#: 존경의 '-주시-'와 방향이 정반대라 사기와 정상을 가른다.
#:     사기  "제가 알려드리는 계좌로"   화자가 계좌를 준다
#:     정상  "계좌번호 알려주시면"      청자가 계좌를 준다
HUMBLE = ("드리", "주")

#: 겸양 앞에 오는 '지정' 동사 어간.
DESIGNATE_STEMS = ("알려", "불러", "안내해", "안내", "말씀", "지정해", "지정", "찍어")

#: 관형형 어미. '-시-'(존경)를 여기 넣으면 방향 구분이 무너지므로 넣지 않는다.
ADNOMINAL = ("는", "신", "ㄴ", "온")

#: 지정의 대상 — 돈이 갈 곳.
DESTINATION = ("계좌", "곳", "번호", "주소", "데로", "쪽", "통장")

#: 대상과 동사 사이에 끼어들 수 있는 음절 수.
#: `GAP_MAX_SYLLABLES`와 같은 이유로 작게 잡는다 — 멀면 같은 표현이 아니다.
INNER_GAP = 8

#: 관형형과 목적지 사이의 수식어. "안내드리는 **학원** 계좌로"처럼 끼어든다.
MODIFIER_GAP = 4


def _alt(items: tuple[str, ...]) -> str:
    """정규식 선택지. 긴 것부터 놓아야 '에게'가 '에'에 먹히지 않는다."""
    return "|".join(re.escape(x) for x in sorted((i for i in items if i), key=len,
                                                 reverse=True))


@dataclass(frozen=True)
class MorphRule:
    """형태 규칙 하나. 어느 단계에 몇 점을 주는지 함께 들고 다닌다."""

    id: str
    target: str          # "S1"~"S8" 또는 critical id
    label: str           # 근거 패널에 그대로 보여줄 이름
    regex: re.Pattern[str]
    score: float = 1.0
    rationale: str = ""

    def find(self, sentence: str) -> MatchSpan | None:
        """정규화된 문장에서 찾는다. 인덱스가 곧 음절 위치다."""
        m = self.regex.search(normalize(sentence))
        if m is None:
            return None
        return MatchSpan(self.label, "morph", m.start(), m.end(), 0)


def _silence_rule() -> MorphRule:
    """[대상]에게(는) … 말하지 마 — 고립 유도의 생산적 구성.

    호칭을 요구하지 않는다. 호칭은 무한하기 때문이다.
    """
    pat = (f"(?:{_alt(DATIVE)})(?:{_alt(TOPIC)})?"
           f"[가-힣]{{0,{INNER_GAP}}}?"
           f"(?:{_alt(SILENCE_STEMS)})"
           f"(?:시)?(?:{_alt(NEGATION)})")
    return MorphRule(
        id="M-S4-함구",
        target="S4",
        label="~에게 말하지 마",
        regex=re.compile(pat),
        rationale=(
            "여격 조사 + 함구 동사 + 부정형. 표면형을 나열하는 대신 구성을 잡는다. "
            "검증셋 1·3·4차에서 같은 구성의 서로 다른 표면형을 세 번 놓쳤다 — "
            "'형수님한테는 말하지', '창구 직원에게는 말씀하지', '부모님께는 알리지'."
        ),
    )


def _designated_account_rule() -> MorphRule:
    """제가 알려드리는 계좌 — 화자가 즉석에서 지정하는 자금 목적지.

    겸양 '-드리-'만 인정하고 존경 '-시-'는 인정하지 않는다.
    "계좌번호 알려주시면"(정상)이 걸리지 않는 것은 그 때문이다.
    """
    pat = (f"(?:{_alt(DESIGNATE_STEMS)})"
           f"(?:{_alt(HUMBLE)})"
           f"(?:{_alt(ADNOMINAL)})"
           f"[가-힣]{{0,{MODIFIER_GAP}}}?"
           f"(?:{_alt(DESTINATION)})")
    return MorphRule(
        id="M-S5-지정계좌",
        target="S5",
        label="~드리는 계좌",
        regex=re.compile(pat),
        rationale=(
            "겸양 '-드리-'는 **화자가** 준다는 표지다. 존경 '-주시-'와 방향이 반대라 "
            "'계좌번호 알려주시면'(정상)과 '제가 알려드리는 계좌로'(사기)가 갈린다. "
            "한국어 경어법이 판별해 주므로 표현을 늘려도 오탐이 늘지 않는다."
        ),
    )


def build_rules() -> list[MorphRule]:
    return [_silence_rule(), _designated_account_rule()]
